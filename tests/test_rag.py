from app.rag.retriever import (
    add_knowledge,
    search_knowledge
)


# ============================================================
# 1. 测试知识
# ============================================================

documents = [
    "日本地区消费者签收商品后的7天内，可以申请退货。",
    "商品存在质量问题时，公司承担退货运费。",
    "普通退货审核通过后，退款将在3到5个工作日内到账。",
    "商品已经使用且不存在质量问题时，通常不能申请无理由退货。"
]


# ============================================================
# 2. 每条知识的唯一 ID
# ============================================================

ids = [
    "return_policy_001",
    "return_policy_002",
    "refund_policy_001",
    "return_policy_003"
]


# ============================================================
# 3. Metadata
# ============================================================

metadatas = [
    {
        "category": "退货政策",
        "country": "日本"
    },
    {
        "category": "退货政策",
        "country": "日本"
    },
    {
        "category": "退款政策",
        "country": "日本"
    },
    {
        "category": "退货政策",
        "country": "日本"
    }
]


# ============================================================
# 4. 写入知识库
# ============================================================

add_knowledge(
    documents,
    ids,
    metadatas
)


# ============================================================
# 5. 检索：只搜索日本的退货政策
# ============================================================

question = "日本买的商品几天可以退？"

results = search_knowledge(
    question,
    k=3,
    threshold=0.8,
    country="日本",
    category="退货政策"
)


# ============================================================
# 6. 查看结果
# ============================================================

print("===== RAG Metadata Filtering 检索结果 =====")

for item in results:

    print(f"距离：{item['distance']}")

    print(f"内容：{item['text']}")

    print(f"Metadata：{item['metadata']}")

    print()