# 清空旧知识库，并重新建立知识库
# ============================================================

from app.rag.retriever import collection
from app.rag.knowledge import build_knowledge_base


# ============================================================
# 1. 获取当前所有知识 ID
# ============================================================

result = collection.get()

ids = result["ids"]

print(f"当前知识库共有 {len(ids)} 条记录")


# ============================================================
# 2. 删除旧知识
# ============================================================

if ids:
    collection.delete(
        ids=ids
    )

    print(f"已删除 {len(ids)} 条旧记录")
else:
    print("当前知识库为空，无需删除")


# ============================================================
# 3. 重新建立知识库
# ============================================================

count = build_knowledge_base()

print(f"重新建立知识库完成，共写入 {count} 个 Chunk")


# ============================================================
# 4. 查看最终知识库
# ============================================================

result = collection.get()

print()
print("===== 当前知识库 =====")

for knowledge_id in result["ids"]:
    print(knowledge_id)