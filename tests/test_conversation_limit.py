# ============================================================
# tests/test_conversation_limit.py
# 测试 Conversation Memory 历史窗口
# ============================================================

from app.memory.conversation import (
    add_message,
    get_conversation,
    clear_conversation
)


# ============================================================
# 1. 测试用户
# ============================================================

user_id = "memory_limit_test"


# ============================================================
# 2. 清空旧数据
# ============================================================

clear_conversation(user_id)


# ============================================================
# 3. 写入 6 轮对话
# ============================================================

for i in range(1, 7):

    add_message(
        user_id,
        "user",
        f"第{i}轮用户消息"
    )

    add_message(
        user_id,
        "assistant",
        f"第{i}轮助手回答"
    )


# ============================================================
# 4. 读取 Memory
# ============================================================

history = get_conversation(user_id)


# ============================================================
# 5. 输出结果
# ============================================================

print("\n===== Conversation Memory =====")

for message in history:
    print(message)


# ============================================================
# 6. 检查最多只保留 5 轮
# ============================================================

assert len(history) == 10

assert history[0]["content"] == "第2轮用户消息"

assert history[-1]["content"] == "第6轮助手回答"


print("\n===== 历史窗口测试通过 =====")


# ============================================================
# 7. 清理测试数据
# ============================================================

clear_conversation(user_id)