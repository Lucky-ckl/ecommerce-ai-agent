from app.rag.chunker import split_text


# ============================================================
# 1. 测试文本
# ============================================================

text = (
    "日本地区消费者签收商品后的7天内，可以申请退货。"
    "商品存在质量问题时，公司承担退货运费。"
    "普通退货审核通过后，退款将在3到5个工作日内到账。"
)


# ============================================================
# 2. 执行切块
# ============================================================

chunks = split_text(
    text,
    chunk_size=30,
    overlap=5
)


# ============================================================
# 3. 输出结果
# ============================================================

print("===== Chunk 切分结果 =====")

for index, chunk in enumerate(chunks):

    print(f"Chunk {index}:")
    print(chunk)
    print(f"长度：{len(chunk)}")
    print()