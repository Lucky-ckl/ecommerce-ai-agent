# ============================================================
# app/agent/language.py
# 多语言应答
#
# 跨境电商场景下用户可能用中文、英文、日文提问，
# 如果一律用中文回答，体验很差。
#
# 这里用字符特征判断语言（不调 LLM，零成本）：
#   日文：假名（平假名 / 片假名）
#   韩文： Hangul
#   中文：汉字
#   其他：拉丁字母 → 按英文处理
# ============================================================


def detect_language(text):
    """
    返回语言代码：ja / ko / zh / en
    """

    message = text or ""

    # --------------------------------------------------------
    # 日文假名
    # --------------------------------------------------------

    for char in message:

        code = ord(char)

        # 平假名 U+3040–U+309F
        # 片假名 U+30A0–U+30FF
        if 0x3040 <= code <= 0x30FF:

            return "ja"

    # --------------------------------------------------------
    # 韩文
    # --------------------------------------------------------

    for char in message:

        code = ord(char)

        # Hangul 音节 U+AC00–U+D7AF
        if 0xAC00 <= code <= 0xD7AF:

            return "ko"

    # --------------------------------------------------------
    # 汉字（中日韩统一表意文字）
    # 上面已经排除日文假名，这里按中文处理
    # --------------------------------------------------------

    for char in message:

        code = ord(char)

        if 0x4E00 <= code <= 0x9FFF:

            return "zh"

    # --------------------------------------------------------
    # 默认英文
    # --------------------------------------------------------

    return "en"


# ============================================================
# 语言 → 回答指令
# ============================================================

LANGUAGE_INSTRUCTIONS = {

    "zh": "请使用简体中文回答。",

    "en": (
        "Please answer in English. "
        "Keep the same friendly tone."
    ),

    "ja": (
        "日本語で回答してください。"
        "丁寧かつ親しみやすいトーンでお願いします。"
    ),

    "ko": (
        "한국어로 답변해 주세요. "
        "친근한 톤을 유지해 주세요."
    ),
}


def build_language_hint(text):
    """
    生成追加到用户消息里的语言指令。
    模型看到后会用对应语言回答。
    """

    language = detect_language(text)

    instruction = LANGUAGE_INSTRUCTIONS.get(
        language,
        LANGUAGE_INSTRUCTIONS["en"]
    )

    return language, f"\n\n[应答语言要求] {instruction}"
