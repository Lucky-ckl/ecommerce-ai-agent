# ============================================================
# 1. 创建一个新的 State
# ============================================================

def create_state():

    return {
        # ----------------------------------------------------
        # 当前是否有等待用户确认的操作
        # ----------------------------------------------------
        "pending_action": None
    }


# ============================================================
# 2. 保存待确认操作
# ============================================================

def set_pending_action(state, tool_name, arguments):

    state["pending_action"] = {
        "tool_name": tool_name,
        "arguments": arguments
    }


# ============================================================
# 3. 获取待确认操作
# ============================================================

def get_pending_action(state):

    return state["pending_action"]


# ============================================================
# 4. 清除待确认操作
# ============================================================

def clear_pending_action(state):

    state["pending_action"] = None